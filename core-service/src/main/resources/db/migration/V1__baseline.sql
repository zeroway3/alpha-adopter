-- Flyway 도입 시점(2026-10-26)까지 ddl-auto: update로 쌓여온 스키마를 그대로 고정한
-- 베이스라인. 이미 이 스키마로 떠 있는 환경(배포된 환경 등)에서는
-- spring.flyway.baseline-on-migrate=true + baseline-version=1 설정 덕분에 Flyway가 이 파일을
-- 실제로 실행하지 않고 "이미 적용됨"으로만 기록한다. 반대로 빈 DB(로컬 신규 셋업, 테스트용
-- Testcontainers)에서는 이 파일이 그대로 실행되어 스키마를 처음부터 만든다. 둘 다 같은 결과가
-- 나와야 하므로, 실제 운영 Postgres(16)에서 pg_dump --schema-only로 뽑은 내용을 그대로 썼다
-- (Hibernate가 매핑을 보고 추측해서 손으로 다시 쓰면 제약조건·인덱스가 미묘하게 어긋날 위험이
-- 있어 일부러 손으로 쓰지 않았다).

CREATE TABLE admin_audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    changed_by character varying(255) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    new_role character varying(255) NOT NULL,
    previous_role character varying(255) NOT NULL,
    reason character varying(255) NOT NULL,
    target_email character varying(255) NOT NULL,
    target_user_id bigint NOT NULL
);

CREATE TABLE news_articles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collected_at timestamp(6) with time zone NOT NULL,
    description text NOT NULL,
    link character varying(1000) NOT NULL,
    original_link character varying(1000),
    published_at timestamp(6) with time zone NOT NULL,
    title character varying(500) NOT NULL,
    CONSTRAINT uknov7ss8jeu61pebk4dirxh8rp UNIQUE (link)
);

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    email character varying(255) NOT NULL,
    is_member boolean NOT NULL,
    password_hash character varying(255),
    role character varying(20) DEFAULT 'USER'::character varying NOT NULL,
    CONSTRAINT uk6dotkott2kjsp8vw4d0m25fb7 UNIQUE (email),
    CONSTRAINT users_role_check CHECK (((role)::text = ANY ((ARRAY['USER'::character varying, 'ADMIN'::character varying])::text[])))
);

CREATE TABLE subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    keyword character varying(255) NOT NULL,
    type character varying(255) NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT subscriptions_type_check CHECK (((type)::text = ANY ((ARRAY['KEYWORD'::character varying, 'STOCK_CODE'::character varying])::text[]))),
    CONSTRAINT fkhro52ohfqfbay9774bev0qinr FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clicked_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone NOT NULL,
    personalization_score double precision,
    read_at timestamp(6) with time zone,
    relevance_score integer,
    sent_at timestamp(6) with time zone,
    status character varying(255) NOT NULL,
    news_article_id bigint NOT NULL,
    subscription_id bigint NOT NULL,
    CONSTRAINT notifications_status_check CHECK (((status)::text = ANY ((ARRAY['MATCHED'::character varying, 'SENT'::character varying, 'FAILED'::character varying])::text[]))),
    CONSTRAINT fkdbw82an9cva7l8v438181yhdr FOREIGN KEY (news_article_id) REFERENCES news_articles(id),
    CONSTRAINT fke782fmwh46b2q4f9gm1wpr7w4 FOREIGN KEY (subscription_id) REFERENCES subscriptions(id)
);

CREATE INDEX idx_notifications_created_at ON notifications USING btree (created_at);
CREATE INDEX idx_notifications_news_article_id ON notifications USING btree (news_article_id);
CREATE INDEX idx_notifications_status ON notifications USING btree (status);
CREATE INDEX idx_notifications_sub_created_id ON notifications USING btree (subscription_id, created_at, id);
CREATE INDEX idx_subscriptions_keyword ON subscriptions USING btree (keyword);
CREATE INDEX idx_subscriptions_user_id ON subscriptions USING btree (user_id);
