-- 수집기 보강: 키워드별 마지막 수집 지점(누락 구간 감지용)과, 사람이 확인해야 하는 수집 이상
-- 기록(누락 가능성·호출 실패·발행 실패). 정상 수집 현황은 Micrometer 지표(news.collector.*)로 본다.

CREATE TABLE collector_checkpoints (
    keyword character varying(255) PRIMARY KEY,
    last_published_at timestamp(6) with time zone NOT NULL,
    last_link character varying(1000) NOT NULL,
    updated_at timestamp(6) with time zone NOT NULL
);

CREATE TABLE collector_incidents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keyword character varying(255) NOT NULL,
    type character varying(30) NOT NULL,
    detail character varying(1000) NOT NULL,
    occurred_at timestamp(6) with time zone NOT NULL
);

CREATE INDEX idx_collector_incidents_occurred_at ON collector_incidents (occurred_at DESC);
